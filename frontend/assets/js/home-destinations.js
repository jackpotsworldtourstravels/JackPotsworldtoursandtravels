'use strict';
/* ===========================================================================
   destinations.js — the homepage Destinations shelf
   ===========================================================================
   NOTHING IN THIS FILE NAMES A PLACE. Grep it for any city or country you can
   think of and it will come back empty: every card, every location chip and
   every label comes out of the API. There is no fallback list, and there
   deliberately is not one — if the API cannot be reached the section says so
   and offers a retry, because a shelf quietly backfilled with hardcoded cities
   is a page telling the customer something the business has not said.

   ONE ENDPOINT, ONE REQUEST:

       GET /api/customer/destinations                  once, on page load

   So this section costs exactly one request whatever the catalogue's size
   (spec §31). It used to make a second call to fetch a destination's locations
   into an expanding in-page panel; a card now navigates to
   /destination/{slug}, where those locations are the filter chips above the
   hotels themselves — so the second request belongs to that page, made once
   the customer has actually asked to see it.

   THE ID IS THE KEY, NEVER THE NAME. The card's href is built from
   `destination.id` — the slug the API hands out. There is no branch anywhere
   that compares a display name and no map from name to URL, which is what
   makes this work for a destination nobody has thought of yet.

   WHY A SEPARATE FILE rather than more of app.js: it owns one section, it is
   the only thing that talks to these two endpoints, and if the section is ever
   dropped this file and one <script> tag go with it.
   =========================================================================== */

(function () {
  const grid = document.getElementById('jwDestGrid');
  const statusEl = document.getElementById('jwDestStatus');
  if (!grid || !statusEl) return;             // not the landing page

  const API = '/api/customer/destinations';

  /* How many cards before the shelf collapses to a "show all" (spec §18/§19).
     Not a cap on what the API may return — everything it sends is rendered,
     this only decides how much is visible before the button is pressed. Nine
     is three full rows at the widest layout and two at the narrowest, so the
     fold always lands on a complete row rather than mid-way through one. */
  const FIRST_SHOWN = 9;

  /* THE LOCATIONS PANEL IS GONE, and with it its cache, its in-flight guard
     and its selection state. A card used to expand a list of locations in
     place; it now navigates to /destination/{slug}, where those same
     locations are the filter chips and the hotels are actually shown. One
     screen does the job two half-screens were doing. */
  let expanded = false;
  let destinations = [];

  /* COMING BACK TO THE SHELF. A card navigates away, and Back reloads this
     page: the shelf starts empty until its fetch answers, so the browser's
     own scroll restoration had nothing tall enough to land on and put the
     traveller at the top of the hero — with the shelf folded back to nine,
     so the card they had opened from "View all" was not even on the page.
     The expansion and the scroll position are kept on THIS history entry
     (history.state, not storage: they describe this visit to this page and
     nothing else), and put back only on a back/forward arrival. */
  const KEY = 'jwDest';
  const navType = (() => {
    try { return (performance.getEntriesByType('navigation')[0] || {}).type || ''; } catch (e) { return ''; }
  })();
  const saved = (navType === 'back_forward' && history.state && history.state[KEY]) || null;
  if (saved && saved.expanded) expanded = true;
  const remember = extra => {
    try {
      const s = Object.assign({}, history.state || {});
      s[KEY] = Object.assign({}, s[KEY] || {}, { expanded }, extra || {});
      history.replaceState(s, '');
    } catch (e) { /* a sandboxed frame may refuse; the shelf still works */ }
  };
  /* The position is read as the page is left, whichever way it is left —
     as an offset from the shelf when the shelf was on screen or above it.
     Coming back from a destination is exactly when "Recommended for you"
     (jw-foryou.js) first appears ABOVE the shelf, so a raw scrollY would
     land short by that section's height. */
  const gridTop = () => grid.getBoundingClientRect().top + window.scrollY;
  window.addEventListener('pagehide', () => {
    const y = Math.round(window.scrollY);
    const onShelf = y + window.innerHeight > gridTop();
    remember({ y, rel: onShelf ? Math.round(y - gridTop()) : null });
  });
  let restored = false;

  /* IMAGE KEY -> FILE, AND THE MANIFEST IS THE ONLY THING THAT DECIDES.
     destination-images.js is generated by scripts/fetch_destination_images.py
     and lists the keys that actually shipped art; the path is derived from the
     key, exactly as hotel-results.js derives hotel art from HOTEL_IMAGE_FILES.

     THE KEY COMES FROM THE API, never from the name or the slug. Today the
     backend happens to set image_key = slug, and reading d.slug here would look
     identical and be wrong: it would move "which picture does Goa get" out of
     the data and into the browser, and the next destination whose art is not
     named after it would break. If the API sends no key, or sends one nothing
     shipped for, this returns null and the card keeps its tint.

     Two widths, so a phone does not download desktop art — the manifest
     guarantees both files exist for any listed key. */
  const artFor = key => {
    if (!key) return null;
    if (typeof DESTINATION_IMAGE_FILES !== 'object' || !DESTINATION_IMAGE_FILES) return null;
    const stamp = DESTINATION_IMAGE_FILES[key];
    if (!stamp) return null;
    const dir = (typeof DESTINATION_IMAGE_DIR === 'string')
      ? DESTINATION_IMAGE_DIR : 'assets/destinations/';
    /* ?v=<stamp> WHEN THE MANIFEST CARRIES ONE. The path is derived from the
       key, so replacing a photograph changes the bytes behind a URL that does
       not change - and a browser that has been here keeps the old picture.
       The manifest's value is a content stamp of that file, so the URL moves
       when the picture does. An older manifest whose values are `true` yields
       no query and behaves exactly as before. */
    const v = (typeof stamp === 'string') ? '?v=' + stamp : '';
    /* `large` is the 1600w file the editorial layout's featured cards want on
       a 2x screen. Every slug in the regenerated manifest ships it; the
       srcset lets the browser pick, so a phone never fetches it. */
    return {
      src: dir + key + '.webp' + v,
      small: dir + key + '-480.webp' + v,
      large: dir + key + '-1600.webp' + v,
    };
  };

  const esc = s => String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

  /* -------------------------------------------------------------------------
     Fetching. api.js is the product's request layer; this uses it when it is
     present so timeouts, base URL and error shaping stay in one place, and
     falls back to fetch() so the section works on a page that has not loaded
     it. Both routes are PUBLIC — no key, no token, nothing secret leaves here
     (spec §24).
     ---------------------------------------------------------------------- */
  async function getJson(path, signal) {
    const res = await fetch(path, {
      signal,
      headers: { Accept: 'application/json' },
      credentials: 'same-origin',
    });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    return res.json();
  }

  /* -------------------------------------------------------------------------
     The shelf
     ---------------------------------------------------------------------- */
  function cardHtml(d, i, eager) {
    /* WHAT IS ON A CARD IS WHAT THE API SENT. `image` is a key, not a URL —
       the same keys the hotel and package catalogues use — and when it is null
       the card keeps the tinted ground rather than borrowing a photograph of
       somewhere it is not. No description is printed because the destinations
       response does not carry one, and inventing a line of travel copy per
       city is exactly what this section replaced.

       THE STAY/TRIP COUNTS ARE GONE, with the derivation that produced them.
       While a destination WAS its inventory the API could say "5 stays"; now
       that geography is its own table (migration 0070) nothing joins the two,
       and printing a count would mean guessing at a join the backend
       deliberately has not made. `country` is what the row actually carries. */
    const meta = [];
    if (d.country) meta.push(d.country);

    const art = artFor(d.image);
    /* onerror, not just a missing-key check. A key can be listed and the file
       still fail — a bad deploy, a proxy, a cache miss — and the one thing the
       card must never show is the browser's broken-image glyph. Removing the
       <img> uncovers the tinted ground underneath it, which is the same
       fallback a destination with no art at all gets. */
    /* `loading` IS DECIDED BY WHY THE CARD IS BEING DRAWN. On first paint the
       shelf is nine cards and the lower ones are lazy, so a phone never fetches
       art it will not see. But "View all" re-renders the whole grid, and a card
       that is added below the fold and left lazy never loads until it is
       scrolled to — so its <img> sits empty (naturalWidth 0) behind the reveal
       animation, which is exactly the "images not showing after View all" bug.
       When the traveller has asked to see everything, every card loads eagerly
       so none of them is a blank frame waiting for a scroll that may not come. */
    const loading = eager ? 'eager' : 'lazy';
    const picture = art
      ? '<img class="jw-dest-img" src="' + esc(art.src) + '"'
        + ' srcset="' + esc(art.small) + ' 480w, ' + esc(art.src) + ' 960w, ' + esc(art.large) + ' 1600w"'
        /* The editorial grid: a featured card is ~58% of the content width
           on a desktop, a small one ~42%; below 1024 they are half or full. */
        + ' sizes="(max-width: 640px) 100vw, (max-width: 1024px) 50vw, 58vw"'
        + ' alt="' + esc(d.name) + '" loading="' + loading + '" decoding="async"'
        + ' onerror="this.remove()">'
      : '';

    /* A LINK, NOT A BUTTON. The card opens /destination/{slug} — the
       destination's famous locations (destination.js), each with a "View
       Hotels" link on to /hotels/{destination}/{location}. It no longer jumps
       straight to hotels. It navigates, so it has to behave like a link: middle-click
       and ctrl-click open a tab, the status bar shows the target, and a
       crawler can follow it. It was a button while clicking only expanded an
       in-page panel; now that it navigates, an anchor is the honest element.

       The href is built from the id the API sent. Nothing here maps a name to
       a URL, so a destination added through the destinations API gets a
       working card and a working page with no change to this file. */
    const href = 'destination/' + encodeURIComponent(d.id);

    /* The numeral and the arrow are the editorial layout's furniture: a
       running count down the shelf and a "go" mark that moves on hover. Both
       are decoration — the aria-label already names the card — so both are
       aria-hidden. The count is the card's position, not anything the API
       says about the place. */
    const num = String(i + 1).padStart(2, '0');

    return '<a role="listitem" class="jw-dest-card"'
      + ' href="' + esc(href) + '"'
      + ' data-dest-id="' + esc(d.id) + '"'
      + ' aria-label="Explore ' + esc(d.name) + '">'
      + '<span class="jw-dest-art">' + picture + '<span class="jw-dest-scrim"></span></span>'
      + '<span class="jw-dest-num" aria-hidden="true">' + num + '</span>'
      + '<span class="jw-dest-body">'
      + '<span class="jw-dest-name">' + esc(d.name) + '</span>'
      + (meta.length ? '<span class="jw-dest-meta">' + esc(meta.join(' · ')) + '</span>' : '')
      + '<span class="jw-dest-go" aria-hidden="true">Explore'
      + '<svg viewBox="0 0 24 24"><path d="M5 12h14M13 6l6 6-6 6"/></svg></span>'
      + '</span></a>';
  }

  function paintShelf() {
    const shown = expanded ? destinations : destinations.slice(0, FIRST_SHOWN);
    /* Eager once the shelf is expanded: the traveller pressed "View all", so
       every card's photograph should load now rather than wait to be scrolled
       past. On the first, collapsed paint the lower cards stay lazy. */
    grid.innerHTML = shown.map((d, i) => cardHtml(d, i, expanded)).join('');
    /* THE ENTRANCE BELONGS TO ONE ENGINE. On the homepage home-cinema.js
       owns the cards' arrival, depth and photograph develop (GSAP); handing
       them to JWMotion as well would put a CSS transition and a GSAP tween
       on the same transform. HomeCinema.cards() answers false when it cannot
       run (script missing, reduced motion is handled inside it), and the
       site's own reveal takes over — so the cards are never left hidden. */
    const cinema = typeof HomeCinema !== 'undefined' && HomeCinema.cards(grid);
    if (!cinema && typeof JWMotion !== 'undefined') JWMotion.grid(grid);
    grid.setAttribute('aria-busy', 'false');

    const rest = destinations.length - shown.length;
    let more = document.getElementById('jwDestMore');
    if (rest > 0) {
      if (!more) {
        more = document.createElement('button');
        more.type = 'button';
        more.id = 'jwDestMore';
        more.className = 'jw-dest-more';
        more.addEventListener('click', () => {
          expanded = true;
          remember();
          paintShelf();
          /* The button is gone, and focus went with it to <body>. Hand it
             to the first card the click revealed — where a keyboard user
             was heading — without scrolling the page to it. */
          const first = grid.children[FIRST_SHOWN];
          if (first) { try { first.focus({ preventScroll: true }); } catch (e) { first.focus(); } }
        });
        grid.insertAdjacentElement('afterend', more);
      }
      more.textContent = 'View all ' + destinations.length + ' destinations';
    } else if (more) {
      more.remove();
    }
    statusEl.textContent = '';
    restoreScroll();
  }

  /** Once, after the first paint of a back/forward arrival: put the page
   *  back where it was left, if the browser could not. Deferred past
   *  HomeCinema's own ScrollTrigger.refresh (60ms), which measures the
   *  shelf it has just been handed; a traveller who has already scrolled
   *  somewhere else is left there. */
  function restoreScroll() {
    if (restored || !saved || typeof saved.y !== 'number') return;
    restored = true;
    setTimeout(() => {
      const target = typeof saved.rel === 'number' ? Math.round(gridTop() + saved.rel) : saved.y;
      if (Math.abs(window.scrollY - target) < 40) return;     // the browser managed it
      if (window.scrollY > target + 40) return;               // they moved on past it
      window.scrollTo({ top: target, behavior: 'instant' });
    }, 120);
  }

  function shelfMessage(text, retry) {
    grid.innerHTML = '';
    grid.setAttribute('aria-busy', 'false');
    statusEl.textContent = text;
    const existing = document.getElementById('jwDestRetry');
    if (existing) existing.remove();
    if (!retry) return;
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.id = 'jwDestRetry';
    btn.className = 'jw-dest-retry';
    btn.textContent = 'Try again';
    btn.addEventListener('click', () => { btn.remove(); loadDestinations(); });
    statusEl.insertAdjacentElement('afterend', btn);
  }

  async function loadDestinations() {
    grid.setAttribute('aria-busy', 'true');
    statusEl.textContent = 'Loading destinations…';
    try {
      const rows = await getJson(API);
      destinations = Array.isArray(rows) ? rows.filter(d => d && d.id && d.name) : [];
      if (!destinations.length) {
        /* The catalogue answered and had nothing in it. That is a real state,
           not a failure, and it gets no retry button — pressing it would ask
           the same question and get the same true answer. */
        shelfMessage('No destinations are listed yet.', false);
        return;
      }
      paintShelf();
    } catch (err) {
      /* The customer is told what to do, not what broke. The detail goes to
         the console for whoever is debugging (spec §15). */
      console.warn('[destinations] list failed:', err && err.message);
      shelfMessage('Unable to load destinations. Please try again.', true);
    }
  }

  loadDestinations();
})();
